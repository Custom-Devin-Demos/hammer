def test_backup_s3():
    source = make_bucket("public", bindings=buckets["public-all-users"]["Bindings"])
    bucket = GCPBucket(make_account(mock.Mock()), source, source.get_iam_policy().bindings)
    s3_client = mock.Mock()
    s3_client.head_object.side_effect = ClientError({"Error": {"Code": "404"}}, "HeadObject")

    path = bucket.backup_s3(s3_client, "backup-bucket")

    assert path.startswith(f"gcp_bucket_policies/{PROJECT_ID}/public_") and path.endswith(".json")
    kwargs = s3_client.put_object.call_args[1]
    assert kwargs["Bucket"] == "backup-bucket"
    assert kwargs["Key"] == path
    assert json.loads(kwargs["Body"])["bindings"] == buckets["public-all-users"]["Bindings"]


