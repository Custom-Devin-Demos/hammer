@pytest.mark.parametrize("enforce", [False, True])
def test_restrict(enforce):
    source = make_bucket("public",
                         bindings=buckets["public-all-users"]["Bindings"],
                         acl=buckets["public-legacy-acl"]["ACL"],
                         uniform=False)
    client = mock.Mock()
    client.list_buckets.return_value = [source]
    checker = GCPBucketsPublicAccessChecker(make_account(client))
    assert checker.check()
    bucket = checker.get_bucket("public")
    assert bucket.public

    assert bucket.restrict(enforce_public_access_prevention=enforce)

    policy = source.set_iam_policy.call_args[0][0]
    assert GCPStorageOperations.get_public_bindings(policy.bindings) == {}
    assert {"role": "roles/storage.objectViewer", "members": ["user:alice@example.com"]} in policy.bindings
    source.acl.save.assert_called_once_with(acl=[{"entity": "project-owners-123", "role": "OWNER"}])
    if enforce:
        assert source.iam_configuration.public_access_prevention == "enforced"
        source.patch.assert_called_once_with()
    else:
        source.patch.assert_not_called()


