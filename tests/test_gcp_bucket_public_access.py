class FakePolicy(object):
    """ Minimal `google.api_core.iam.Policy` replacement """
    def __init__(self, bindings):
        self.bindings = [dict(binding) for binding in bindings]
        self.version = 3
        self.etag = "BwXyz"


def make_bucket(name, bindings=None, acl=None, uniform=True, pap="inherited", labels=None, location="US"):
    bucket = mock.Mock()
    bucket.name = name
    bucket.location = location
    bucket.labels = labels or {}
    bucket.iam_configuration = mock.Mock()
    bucket.iam_configuration.uniform_bucket_level_access_enabled = uniform
    bucket.iam_configuration.public_access_prevention = pap
