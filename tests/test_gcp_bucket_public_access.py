def run_remediation(bucket, batch=True, confirmed=False, restrict_result=True):
    remediation = importlib.import_module("remediation.clean_gcp_bucket_public_access")
    config = make_config()
    issue = make_issue(reported="2025-12-01T00:00:00+00:00")
    cleaner = remediation.CleanGCPBucketPublicAccess(config)
    remediator = mock.Mock()
    remediator.candidates.return_value = [(PROJECT_ID, PROJECT_NAME, issue)]
    remediator.account.return_value = make_account(mock.Mock())
    cleaner.remediator = remediator
    checker = mock.Mock()
    checker.check.return_value = True
    checker.get_bucket.return_value = bucket
    if bucket is not None:
        bucket.restrict.return_value = restrict_result
        bucket.backup_s3.return_value = f"gcp_bucket_policies/{PROJECT_ID}/backup.json"
    with mock.patch.object(remediation, "Account") as main_account, \
         mock.patch.object(remediation, "GCPBucketsPublicAccessChecker", return_value=checker), \
         mock.patch.object(remediation, "confirm", return_value=confirmed) as confirm:
        cleaner.clean_gcp_bucket_public_access(batch=batch)
    checker.check.assert_called_once_with(ids=["public-all-users"])
    return remediator, confirm, main_account, issue


def test_remediation_batch():
    bucket = mock.Mock(public=True)
    bucket.name = "public-all-users"
    remediator, confirm, main_account, issue = run_remediation(bucket)
    confirm.assert_not_called()
    bucket.backup_s3.assert_called_once_with(main_account.return_value.client.return_value, "backup-bucket")
    bucket.restrict.assert_called_once_with(enforce_public_access_prevention=True)
    args, kwargs = remediator.report_remediation.call_args
    assert args[0] is issue
    assert "was remediated by hammer" in args[3]
    assert kwargs["succeed"] is True


