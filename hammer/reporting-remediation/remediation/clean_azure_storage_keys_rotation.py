"""
Class to remediate Azure storage accounts with not rotated access keys (regenerate stale keys).
"""
import sys
import logging
import argparse


from library.logger import set_logging, add_cw_logging
from library.config import Config
from library.ddb_issues import AzureStorageKeyRotationIssue
from library.multicloud_reporting import MultiCloudIssueRemediator
from library.azure.storage_keys import StorageKeysChecker
from library.utility import confirm
from library.utility import SingletonInstance, SingletonInstanceException


class CleanAzureStorageKeysRotation:
    """ Class to regenerate stale Azure storage account access keys """
    def __init__(self, config):
        self.config = config
        self.remediator = MultiCloudIssueRemediator(config, config.azureStorageKeys, AzureStorageKeyRotationIssue)

    def clean_storage_keys(self, batch=False):
        """ Class method to remediate Azure storage account stale access keys """
        module_config = self.config.azureStorageKeys

        for account_id, account_name, issue in self.remediator.candidates():
            name = issue.issue_id
            title = self.remediator.account_title(account_id, account_name)
            try:
                account = self.remediator.account(account_id)
                checker = StorageKeysChecker(account=account,
                                             now=self.config.now,
                                             rotation_criteria_days=module_config.rotation_criteria_days)
                if not checker.check(ids=[name]):
                    continue

                storage_account = checker.get_storage_account(name)
                if storage_account is None:
                    logging.debug(f"Storage account '{name}' was removed by user")
                    continue

                stale_keys = [key.name for key in storage_account.stale_keys]
                if not stale_keys:
                    logging.debug(f"Storage account '{name}' has no stale access keys anymore")
                    continue

                keys = ", ".join(stale_keys)
                if not batch and \
                   not confirm(f"Do you want to regenerate '{keys}' access key(s) of storage account '{name}' "
                               f"in {title} (applications using these keys will lose access)", False):
                    continue

                logging.debug(f"Regenerating '{keys}' access key(s) of storage account '{name}'")
                regenerated, failed = [], []
                for key_name in stale_keys:
                    try:
                        storage_account.regenerate_key(key_name)
                        regenerated.append(key_name)
                    except Exception:
                        logging.exception(f"Failed to regenerate '{key_name}' access key of storage account '{name}'")
                        failed.append(key_name)

                remediation_succeed = not failed
                if remediation_succeed:
                    comment = (f"Stale access key(s) '{keys}' of storage account '{name}' issue "
                               f"in {title} "
                               f"was remediated by hammer (keys were regenerated)")
                else:
                    comment = (f"Failed to remediate stale access key(s) '{', '.join(failed)}' "
                               f"of storage account '{name}' issue "
                               f"in {title} "
                               f"due to some limitations. Please, check manually")
                    if regenerated:
                        comment += f" (key(s) '{', '.join(regenerated)}' were regenerated by hammer)"

                self.remediator.report_remediation(issue, account_id, account_name, comment, remediation_succeed)
            except Exception:
                logging.exception(f"Error occurred while regenerating access keys of storage account '{name}' "
                                  f"in {title}")


if __name__ == "__main__":
    module_name = sys.modules[__name__].__loader__.name
    set_logging(level=logging.DEBUG, logfile=f"/var/log/hammer/{module_name}.log")
    config = Config()
    add_cw_logging(config.local.log_group,
                   log_stream=module_name,
                   level=logging.DEBUG,
                   region=config.aws.region)
    try:
        si = SingletonInstance(module_name)
    except SingletonInstanceException:
        logging.error(f"Another instance of '{module_name}' is already running, quitting")
        sys.exit(1)

    parser = argparse.ArgumentParser()
    parser.add_argument('--batch', action='store_true', help='Do not ask confirmation for remediation')
    args = parser.parse_args()

    try:
        class_object = CleanAzureStorageKeysRotation(config)
        class_object.clean_storage_keys(batch=args.batch)
    except Exception:
        logging.exception("Failed to clean Azure storage account stale access keys")
