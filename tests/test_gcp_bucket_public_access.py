def sns_event(payload):
    return {"Records": [{"Sns": {"Message": json.dumps(payload)}}]}


def run_describe(open_issues, request_id=None, whitelist=None, failed=None):
    import describe_gcp_bucket_public_access as describe
    config = make_config(make_module_config(whitelist=whitelist))
    client = mock.Mock()
    client.list_buckets.return_value = make_test_buckets()
    account = make_account(client)
    if failed:
        broken = make_bucket(failed)
        broken.get_iam_policy.side_effect = InternalServerError("boom")
        client.list_buckets.return_value.append(broken)
    payload = {"account_id": PROJECT_ID, "account_name": PROJECT_NAME, "sns_arn": "arn"}
    if request_id:
        payload["request_id"] = request_id
    with mock.patch.object(describe, "Config", return_value=config), \
         mock.patch.object(describe, "Account") as main_account, \
         mock.patch.object(describe, "GCPAccount", return_value=account) as gcp_account, \
         mock.patch.object(describe, "DDB") as ddb, \
         mock.patch.object(describe, "IssueOperations") as ops:
        ops.get_account_open_issues.return_value = open_issues
        describe.lambda_handler(sns_event(payload), None)
    gcp_account.assert_called_once_with(id=PROJECT_ID, name=PROJECT_NAME, credentials=config.gcp.credentials)
    return ops, ddb, main_account


def test_describe_lambda():
    vanished = GCPBucketPublicAccessIssue(PROJECT_ID, "deleted-bucket")
    still_public = GCPBucketPublicAccessIssue(PROJECT_ID, "public-all-users")
    ops, ddb, _ = run_describe([vanished, still_public],
                               whitelist={PROJECT_ID: ["public-authenticated"]})

    updated = {call[0][1].issue_id: call[0][1] for call in ops.update.call_args_list}
    assert set(updated) == {"public-all-users", "public-authenticated", "public-legacy-acl"}
    issue = updated["public-all-users"]
    assert issue.status == IssueStatus.Open
    assert issue.issue_details.provider == "gcp"
    assert issue.issue_details.name == "public-all-users"
    assert issue.issue_details.location == "US"
    assert issue.issue_details.tags == {"owner": "alice"}
    assert issue.issue_details.owner == "alice"
    assert issue.issue_details.public_bindings == {"roles/storage.objectViewer": ["allUsers"]}
    assert updated["public-authenticated"].status == IssueStatus.Whitelisted
    assert updated["public-legacy-acl"].issue_details.public_acls == {"allUsers": ["READER"]}

    resolved = [call[0][1].issue_id for call in ops.set_status_resolved.call_args_list]
    assert resolved == ["deleted-bucket"]
    ddb.track_progress.assert_not_called()


def test_describe_lambda_keeps_failed_bucket_issue():
    failed_issue = GCPBucketPublicAccessIssue(PROJECT_ID, "broken")
    ops, _, _ = run_describe([failed_issue], failed="broken")
    ops.set_status_resolved.assert_not_called()


def test_describe_lambda_api_request():
    _, ddb, _ = run_describe([], request_id="req-1")
    assert ddb.track_progress.call_args[0][1] == "req-1"


