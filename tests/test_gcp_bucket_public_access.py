def ident_test(arg):
    """ Used to build identification string for each autogenerated test (for easy recognition of failed tests) """
    if isinstance(arg, bool):
        return "remediated" if arg else "original"
    elif isinstance(arg, dict):
        # add description for each test
        return arg.get("Description", "")
    return arg


@pytest.mark.parametrize("bucket_name,bucket_details", buckets.items(), ids=ident_test)
def test_bucket(checker, bucket_name, bucket_details):
    """ Actual test for each bucket in `buckets` dict """
    bucket = checker.get_bucket(bucket_name)
